"""RL gateway: OpenAI-compatible proxy between the pi harness and the vLLM policy server.

Responsibilities
  * Route `model: "policy"` (whatever pi sends) to the current policy: the base model for version 0, the
    LoRA adapter `policy-v{N}` afterwards. New versions published by the trainer become active only at the
    next attempt boundary, so every rollout is generated by a single policy version.
  * RLTL;DR insight conditioning (paper Fig. 1 / App. A.2): for agent calls of the active attempt, insert one
    user message per insight right after the task (first user message):
        ==> A previous Attempt {i} on this same task FAILED the verifier. <==
        Hint on what went wrong: {hint}
  * Exact trajectory capture for training: request `return_token_ids` + `logprobs` from vLLM and append one
    record per LLM call (prompt ids, completion ids, behaviour logprobs, policy version, messages as sent)
    to data/attempts/<attempt_id>/calls.jsonl. Training never re-tokenizes chat text.
  * Robustness: waits for vLLM while it is down or restarting (pi only retries a few times), re-registers
    LoRA adapters lost by a vLLM restart, optional pause gate.

Control API (localhost only): GET /control/state, POST /control/attempt, /control/attempt_end,
/control/policy, /control/pause, /control/resume.
Headers on chat requests: X-RL-Kind (agent|insight|eval, default agent), X-RL-Attempt (override attempt id).
"""
import asyncio
import json
import logging
import os
import sys
import time
import uuid

import aiohttp
from aiohttp import web

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from rltldr.config import load_config  # noqa: E402
from rltldr.io_utils import append_jsonl, read_json, write_json_atomic  # noqa: E402

CFG = load_config()
STATE_PATH = CFG.path("gateway_state.json")
UPSTREAM_WAIT_S = 1800          # how long a request waits for a dead/restarting vLLM before failing
STALL_S = 900                   # a stream with no bytes for this long is treated as a wedged server
# Requests from the agent sandbox: only the fields pi sends; sampling is fixed to the policy's settings, so
# hand-made requests cannot inject off-policy samples into the training data.
SANDBOX_FIELDS = {"model", "messages", "tools", "tool_choice", "stream", "stream_options", "max_tokens",
                  "reasoning_effort", "parallel_tool_calls"}
SANDBOX_SAMPLING = {"temperature": 1.0, "top_p": 0.95, "top_k": 20, "min_p": 0.0, "presence_penalty": 0.0,
                    "repetition_penalty": 1.0, "n": 1}
SANDBOX_MAX_TOKENS = 32768
INSIGHT_HEADER = "==> A previous Attempt {i} on this same task FAILED the verifier. <=="
log = logging.getLogger("gateway")


def insight_message_text(idx: int, hint: str) -> str:
    return f"{INSIGHT_HEADER.format(i=idx)}\nHint on what went wrong: {hint}"


class State:
    def __init__(self):
        s = read_json(STATE_PATH, {}) or {}
        # policy = what new attempts use; pending = published by trainer, activated at next attempt start
        self.policy = s.get("policy") or {"name": CFG.base_model_name, "version": 0, "path": None}
        self.pending = s.get("pending")
        self.adapters = s.get("adapters", {})       # name -> path, for re-registration after vLLM restarts
        self.attempt = s.get("attempt")             # {"id", "insights": [{"idx","hint"}], "policy": {...}}
        self.paused = False
        self.gate = asyncio.Event()
        self.gate.set()
        self.lock = asyncio.Lock()

    def save(self):
        write_json_atomic(STATE_PATH, {"policy": self.policy, "pending": self.pending,
                                       "adapters": self.adapters, "attempt": self.attempt})

    def snapshot(self):
        return {"policy": self.policy, "pending": self.pending, "attempt": self.attempt,
                "paused": self.paused, "adapters": sorted(self.adapters)}


ST: State = None  # created inside the event loop
SESSION: aiohttp.ClientSession = None


# ------------------------------------------------------------------------------------------------------
# vLLM helpers
# ------------------------------------------------------------------------------------------------------
async def vllm_load_adapter(name: str, path: str) -> bool:
    try:
        async with SESSION.post(f"{CFG.vllm_url}/v1/load_lora_adapter",
                                json={"lora_name": name, "lora_path": path},
                                timeout=aiohttp.ClientTimeout(total=600)) as r:
            txt = await r.text()
            if r.status == 200 or "already" in txt.lower():
                return True
            log.error("load_lora_adapter %s failed: %s %s", name, r.status, txt[:300])
    except aiohttp.ClientError as e:
        log.error("load_lora_adapter %s error: %s", name, e)
    return False


async def vllm_unload_adapter(name: str) -> None:
    try:
        async with SESSION.post(f"{CFG.vllm_url}/v1/unload_lora_adapter", json={"lora_name": name},
                                timeout=aiohttp.ClientTimeout(total=120)) as r:
            await r.read()
    except aiohttp.ClientError:
        pass


async def vllm_served_models() -> set:
    async with SESSION.get(f"{CFG.vllm_url}/v1/models", timeout=aiohttp.ClientTimeout(total=10)) as r:
        d = await r.json()
    return {m["id"] for m in d.get("data", [])}


async def ensure_adapter_loaded(name: str) -> None:
    """Re-register an adapter that vLLM forgot (restart). No-op for the base model."""
    if name == CFG.base_model_name or name not in ST.adapters:
        return
    try:
        if name in await vllm_served_models():
            return
    except Exception:
        return
    log.warning("adapter %s missing in vLLM; re-loading from %s", name, ST.adapters[name])
    await vllm_load_adapter(name, ST.adapters[name])


