# request rewriting
# ------------------------------------------------------------------------------------------------------
def inject_insights(messages: list, insights: list) -> tuple:
    """Insert one user message per insight right after the first user message (the task)."""
    if not insights:
        return messages, []
    first_user = next((i for i, m in enumerate(messages) if m.get("role") == "user"), None)
    if first_user is None:
        return messages, []
    texts = [insight_message_text(x["idx"], x["hint"]) for x in insights]
    new = messages[: first_user + 1] + [{"role": "user", "content": t} for t in texts] + messages[first_user + 1:]
    return new, [{"idx": x["idx"], "hint": x["hint"], "text": t} for x, t in zip(insights, texts)]


def merge_tool_call_deltas(acc: dict, deltas: list) -> None:
    for d in deltas or []:
        i = d.get("index", 0)
        tc = acc.setdefault(i, {"id": None, "type": "function", "function": {"name": "", "arguments": ""}})
        if d.get("id"):
            tc["id"] = d["id"]
        f = d.get("function") or {}
        if f.get("name"):
            tc["function"]["name"] += f["name"]
        if f.get("arguments"):
            tc["function"]["arguments"] += f["arguments"]


